function P = pfail_linear(N, q)
%PFAIL_LINEAR 传统线性杀伤链的体系完全崩溃概率（式 eq:linear 右半部分）
%
%   P = [1 - (1-q)^3]^N
%
%   输入
%     N : 每类节点数（默认各为 N，共 N 条串行杀伤链）；可为标量
%     q : 单节点战损率，可为数组
%
%   输出
%     P : 与 q 同尺寸的崩溃概率。N 条链彼此独立，全部断裂即体系崩溃。
%
%   注：P 是“全部 N 条链同时断裂”的概率，对应论文 51.29% 的口径。
p = 1 - q;
P = (1 - p.^3).^N;
end
